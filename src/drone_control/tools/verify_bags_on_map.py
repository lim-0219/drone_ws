r"""Check a stitched map against the bag positions generated by make_grass_world.py.

Runs with the STITCHER virtualenv (needs OpenCV + drone_stitch), not the ROS Python:

    cd ~/drone_ws/src/drone-stitching && env -u PYTHONPATH .venv/bin/python -I \
        ~/drone_ws/src/drone_control/tools/verify_bags_on_map.py \
        ~/drone_survey_sessions/<session>/stitch_01 \
        ~/PX4-Autopilot/Tools/simulation/gz/models/trash_bags/bags.json <session_id>

For each bag whose true NED position falls inside the map's valid area, look at the
map colour in a small window around the projected pixel: a bag is 'found' when the
window is clearly not grass (low green dominance or very bright/dark). Reports the
hit rate and the mean positional offset between the projected centre and the
nearest non-grass blob centre.
"""
import json
import sys

import cv2
from drone_stitch.coordinates import MapCoordinates
import numpy as np

run_dir, bags_json = sys.argv[1], sys.argv[2]
frame_id = sys.argv[3] if len(sys.argv) > 3 else None
coords = MapCoordinates(f'{run_dir}/transforms.json')
mapimg = cv2.imread(f'{run_dir}/map.png')
valid = cv2.imread(f'{run_dir}/valid_mask.png', cv2.IMREAD_GRAYSCALE)
bags = json.load(open(bags_json))['bags']
ppm = coords.data['map']['pixels_per_meter']


def is_grass(bgr):
    b, g, r = [float(v) for v in bgr]
    return g > r + 8 and g > b + 20 and 60 < g < 230


found, missed, offsets = [], [], []
for bag in bags:
    try:
        uv = coords.ned_to_pixel([[bag['north_m'], bag['east_m']]], frame_id)[0]
    except ValueError as e:
        print('ned_to_pixel failed:', e)
        sys.exit(2)
    u, v = int(round(uv[0])), int(round(uv[1]))
    if not (0 <= u < valid.shape[1] and 0 <= v < valid.shape[0]) or valid[v, u] == 0:
        continue   # bag outside the mosaic
    half = int(max(bag['length_m'], bag['width_m']) * ppm * 0.9)
    y0, y1 = max(0, v - half), min(valid.shape[0], v + half + 1)
    x0, x1 = max(0, u - half), min(valid.shape[1], u + half + 1)
    window = mapimg[y0:y1, x0:x1]
    nongrass = np.zeros(window.shape[:2], dtype=np.uint8)
    for yy in range(window.shape[0]):
        for xx in range(window.shape[1]):
            if not is_grass(window[yy, xx]):
                nongrass[yy, xx] = 255
    nongrass = cv2.morphologyEx(nongrass, cv2.MORPH_OPEN, np.ones((5, 5), np.uint8))
    n, labels, stats, centroids = cv2.connectedComponentsWithStats(nongrass)
    blobs = [(stats[i, cv2.CC_STAT_AREA], centroids[i]) for i in range(1, n)
             if stats[i, cv2.CC_STAT_AREA] > 0.004 * ppm * ppm]
    expected_area = np.pi * (bag['length_m'] / 2) * (bag['width_m'] / 2) * ppm * ppm
    if blobs:
        area, c = max(blobs, key=lambda t: t[0])
        dx, dy = (c[0] + x0 - u) / ppm, (c[1] + y0 - v) / ppm
        offsets.append(np.hypot(dx, dy))
        found.append((bag['id'], bag['litres'], bag['colour'], round(area / expected_area, 2),
                      round(float(np.hypot(dx, dy)), 2)))
    else:
        missed.append((bag['id'], bag['litres'], bag['colour']))
print(f'bags inside the mosaic: {len(found) + len(missed)}  '
      f'found: {len(found)}  missed: {len(missed)}')
for f in found:
    print('  found  id=%2d %3dL %-17s area_ratio=%.2f offset=%.2f m' % f)
for m in missed:
    print('  MISSED id=%2d %3dL %s' % m)
if offsets:
    print('position offset (projected vs blob centre): mean %.2f m, max %.2f m'
          % (np.mean(offsets), np.max(offsets)))
print('RESULT', 'OK' if found and len(missed) <= max(1, len(found) // 5) else 'CHECK')
